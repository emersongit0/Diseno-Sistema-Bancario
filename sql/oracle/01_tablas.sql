-- No repetir sobre objetos existentes. Si falla, detenerse y compartir el error.
-- Las FK solo corresponden a relaciones reales; auditoría y log son independientes.
-- Longitudes no fijadas por la especificación: nombres/apellidos 100, email 254,
-- descripción 500, mensaje de error 4000; identificadores NUMBER(10).

-- @OBJETO: TBL_CLIENTES
CREATE TABLE TBL_CLIENTES (
    ID_CLIENTE NUMBER(10),
    DNI VARCHAR2(8) CONSTRAINT CK_CLIENTES_DNI_NN NOT NULL,
    NOMBRES VARCHAR2(100 CHAR) CONSTRAINT CK_CLIENTES_NOMBRES_NN NOT NULL,
    APELLIDOS VARCHAR2(100 CHAR) CONSTRAINT CK_CLIENTES_APELLIDOS_NN NOT NULL,
    EMAIL VARCHAR2(254 CHAR) CONSTRAINT CK_CLIENTES_EMAIL_NN NOT NULL,
    CATEGORIA VARCHAR2(7) DEFAULT 'BASICO'
        CONSTRAINT CK_CLIENTES_CATEGORIA_NN NOT NULL,
    FECHA_REGISTRO DATE DEFAULT SYSDATE
        CONSTRAINT CK_CLIENTES_FECHA_NN NOT NULL,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTES_DNI UNIQUE (DNI),
    CONSTRAINT UQ_CLIENTES_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_CLIENTES_DNI CHECK (REGEXP_LIKE(DNI, '^[0-9]{8}$')),
    CONSTRAINT CK_CLIENTES_CATEGORIA CHECK (CATEGORIA IN ('BASICO','GOLD','PREMIUM'))
);
COMMENT ON TABLE TBL_CLIENTES IS 'Titulares del banco y su categoría por saldo total.';
COMMENT ON COLUMN TBL_CLIENTES.ID_CLIENTE IS 'Identificador asignado por SQ_CLIENTE mediante trigger.';
COMMENT ON COLUMN TBL_CLIENTES.DNI IS 'Documento único de ocho dígitos.';
COMMENT ON COLUMN TBL_CLIENTES.NOMBRES IS 'Nombres normalizados a mayúsculas por trigger.';
COMMENT ON COLUMN TBL_CLIENTES.APELLIDOS IS 'Apellidos normalizados a mayúsculas por trigger.';
COMMENT ON COLUMN TBL_CLIENTES.EMAIL IS 'Correo electrónico único del cliente.';
COMMENT ON COLUMN TBL_CLIENTES.CATEGORIA IS 'BASICO, GOLD o PREMIUM según el saldo total.';
COMMENT ON COLUMN TBL_CLIENTES.FECHA_REGISTRO IS 'Fecha de registro del cliente.';
-- @FIN

-- @OBJETO: TBL_CUENTAS
CREATE TABLE TBL_CUENTAS (
    ID_CUENTA NUMBER(10),
    NRO_CUENTA VARCHAR2(12) CONSTRAINT CK_CUENTAS_NRO_NN NOT NULL,
    ID_CLIENTE NUMBER(10) CONSTRAINT CK_CUENTAS_CLIENTE_NN NOT NULL,
    TIPO VARCHAR2(9) CONSTRAINT CK_CUENTAS_TIPO_NN NOT NULL,
    SALDO NUMBER(14,2) DEFAULT 0 CONSTRAINT CK_CUENTAS_SALDO_NN NOT NULL,
    TASA_INTERES_ANUAL NUMBER(5,2),
    ESTADO VARCHAR2(9) DEFAULT 'ACTIVA' CONSTRAINT CK_CUENTAS_ESTADO_NN NOT NULL,
    FECHA_APERTURA DATE DEFAULT SYSDATE CONSTRAINT CK_CUENTAS_FECHA_NN NOT NULL,
    FECHA_ULT_INTERES DATE,
    CONSTRAINT PK_CUENTAS PRIMARY KEY (ID_CUENTA),
    CONSTRAINT UQ_CUENTAS_NRO UNIQUE (NRO_CUENTA),
    CONSTRAINT FK_CUENTAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES TBL_CLIENTES (ID_CLIENTE),
    CONSTRAINT CK_CUENTAS_TIPO CHECK (TIPO IN ('AHORROS','CORRIENTE')),
    CONSTRAINT CK_CUENTAS_ESTADO CHECK (ESTADO IN ('ACTIVA','BLOQUEADA')),
    -- Última barrera; los procedimientos validan el saldo antes de operar.
    CONSTRAINT CK_CUENTAS_SALDO CHECK (SALDO >= 0)
);
COMMENT ON TABLE TBL_CUENTAS IS 'Cuentas en soles; el saldo se mantiene con el trigger de movimientos.';
COMMENT ON COLUMN TBL_CUENTAS.ID_CUENTA IS 'Identificador generado con un único NEXTVAL de SQ_CUENTA.';
COMMENT ON COLUMN TBL_CUENTAS.NRO_CUENTA IS 'Número 191- seguido de ocho dígitos del identificador.';
COMMENT ON COLUMN TBL_CUENTAS.ID_CLIENTE IS 'Titular de la cuenta.';
COMMENT ON COLUMN TBL_CUENTAS.TIPO IS 'AHORROS o CORRIENTE.';
COMMENT ON COLUMN TBL_CUENTAS.SALDO IS 'Saldo vigente en soles, nunca negativo.';
COMMENT ON COLUMN TBL_CUENTAS.TASA_INTERES_ANUAL IS 'Tasa anual porcentual; por ejemplo 3.00 equivale a 3 por ciento.';
COMMENT ON COLUMN TBL_CUENTAS.ESTADO IS 'ACTIVA o BLOQUEADA.';
COMMENT ON COLUMN TBL_CUENTAS.FECHA_APERTURA IS 'Fecha de apertura.';
COMMENT ON COLUMN TBL_CUENTAS.FECHA_ULT_INTERES IS 'Primer día del último mes con intereses aplicados; inicialmente nulo.';
-- @FIN

-- @OBJETO: TBL_MOVIMIENTOS
CREATE TABLE TBL_MOVIMIENTOS (
    ID_MOVIMIENTO NUMBER(10),
    ID_CUENTA NUMBER(10) CONSTRAINT CK_MOV_CUENTA_NN NOT NULL,
    TIPO VARCHAR2(15) CONSTRAINT CK_MOV_TIPO_NN NOT NULL,
    MONTO NUMBER(14,2) CONSTRAINT CK_MOV_MONTO_NN NOT NULL,
    SALDO_POSTERIOR NUMBER(14,2) CONSTRAINT CK_MOV_SALDO_NN NOT NULL,
    FECHA TIMESTAMP CONSTRAINT CK_MOV_FECHA_NN NOT NULL,
    DESCRIPCION VARCHAR2(500 CHAR),
    ID_CUENTA_RELACIONADA NUMBER(10),
    CONSTRAINT PK_MOVIMIENTOS PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_CUENTA FOREIGN KEY (ID_CUENTA) REFERENCES TBL_CUENTAS (ID_CUENTA),
    CONSTRAINT FK_MOV_CUENTA_REL FOREIGN KEY (ID_CUENTA_RELACIONADA) REFERENCES TBL_CUENTAS (ID_CUENTA),
    CONSTRAINT CK_MOV_TIPO CHECK (TIPO IN (
        'DEPOSITO','RETIRO','TRANSF_ENVIADA','TRANSF_RECIBIDA','INTERES','COMISION'
    ))
);
COMMENT ON TABLE TBL_MOVIMIENTOS IS 'Libro de movimientos; cada inserción actualiza el saldo mediante trigger.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.ID_MOVIMIENTO IS 'Identificador asignado por SQ_MOVIMIENTO.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.ID_CUENTA IS 'Cuenta afectada por el movimiento.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.TIPO IS 'Tipo de abono o cargo; determina el signo sobre el saldo.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.MONTO IS 'Importe positivo; validado por TRG_MOVIMIENTOS_BI.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.SALDO_POSTERIOR IS 'Saldo después del movimiento, calculado por trigger.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.FECHA IS 'Instante del movimiento, asignado por trigger.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.DESCRIPCION IS 'Descripción de la operación.';
COMMENT ON COLUMN TBL_MOVIMIENTOS.ID_CUENTA_RELACIONADA IS 'Contraparte de transferencia; nulo en operaciones sin contraparte.';
-- @FIN

-- @OBJETO: TBL_AUDITORIA
CREATE TABLE TBL_AUDITORIA (
    ID_AUDITORIA NUMBER(10),
    TABLA VARCHAR2(30) CONSTRAINT CK_AUDITORIA_TABLA_NN NOT NULL,
    OPERACION VARCHAR2(30) CONSTRAINT CK_AUDITORIA_OPERACION_NN NOT NULL,
    ID_REGISTRO NUMBER(10) CONSTRAINT CK_AUDITORIA_REGISTRO_NN NOT NULL,
    USUARIO_BD VARCHAR2(128 CHAR) DEFAULT USER CONSTRAINT CK_AUDITORIA_USUARIO_NN NOT NULL,
    FECHA TIMESTAMP DEFAULT SYSTIMESTAMP CONSTRAINT CK_AUDITORIA_FECHA_NN NOT NULL,
    DETALLE VARCHAR2(500),
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID_AUDITORIA)
);
COMMENT ON TABLE TBL_AUDITORIA IS 'Trazabilidad de movimientos y cambios de estado, escrita por triggers.';
COMMENT ON COLUMN TBL_AUDITORIA.ID_AUDITORIA IS 'Identificador asignado con SQ_AUDITORIA.';
COMMENT ON COLUMN TBL_AUDITORIA.TABLA IS 'Nombre de la tabla auditada.';
COMMENT ON COLUMN TBL_AUDITORIA.OPERACION IS 'Operación auditada.';
COMMENT ON COLUMN TBL_AUDITORIA.ID_REGISTRO IS 'Identificador del registro auditado; sin FK polimórfica.';
COMMENT ON COLUMN TBL_AUDITORIA.USUARIO_BD IS 'Usuario Oracle que realizó la operación.';
COMMENT ON COLUMN TBL_AUDITORIA.FECHA IS 'Instante de la operación.';
COMMENT ON COLUMN TBL_AUDITORIA.DETALLE IS 'Detalle resumido, hasta 500 bytes.';
-- @FIN

