-- El saldo SOLO lo actualiza TRG_MOVIMIENTOS_AI: los futuros procedimientos
-- insertan movimientos, nunca vuelven a actualizar el saldo.
-- Los triggers de movimientos leen/modifican OTRA tabla (TBL_CUENTAS), no la
-- tabla mutante TBL_MOVIMIENTOS. Así se evita ORA-04091 y el doble descuento.

-- @OBJETO: TRG_CLIENTES_BI
CREATE OR REPLACE TRIGGER TRG_CLIENTES_BI
BEFORE INSERT OR UPDATE OF NOMBRES, APELLIDOS ON TBL_CLIENTES
FOR EACH ROW
BEGIN
    :NEW.NOMBRES := UPPER(:NEW.NOMBRES);
    :NEW.APELLIDOS := UPPER(:NEW.APELLIDOS);
    IF :NEW.ID_CLIENTE IS NULL THEN
        :NEW.ID_CLIENTE := SQ_CLIENTE.NEXTVAL;
    END IF;
END TRG_CLIENTES_BI;
/
-- @FIN

-- @OBJETO: TRG_CUENTAS_BI
CREATE OR REPLACE TRIGGER TRG_CUENTAS_BI
BEFORE INSERT ON TBL_CUENTAS
FOR EACH ROW
DECLARE
    v_id TBL_CUENTAS.ID_CUENTA%TYPE;
BEGIN
    v_id := SQ_CUENTA.NEXTVAL;
    :NEW.ID_CUENTA := v_id;
    :NEW.NRO_CUENTA := '191-' || LPAD(v_id, 8, '0');
END TRG_CUENTAS_BI;
/
-- @FIN

-- @OBJETO: TRG_MOVIMIENTOS_BI
CREATE OR REPLACE TRIGGER TRG_MOVIMIENTOS_BI
BEFORE INSERT ON TBL_MOVIMIENTOS
FOR EACH ROW
DECLARE
    v_saldo TBL_CUENTAS.SALDO%TYPE;
BEGIN
    IF :NEW.MONTO IS NULL OR :NEW.MONTO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Monto inválido: debe ser mayor que cero.');
    END IF;
    SELECT SALDO INTO v_saldo
    FROM TBL_CUENTAS
    WHERE ID_CUENTA = :NEW.ID_CUENTA
    FOR UPDATE WAIT 5;
    :NEW.ID_MOVIMIENTO := SQ_MOVIMIENTO.NEXTVAL;
    :NEW.FECHA := SYSTIMESTAMP;
    -- El AFTER del INSERT anterior ya actualizó TBL_CUENTAS: la COMISION
    -- ve el saldo que dejó TRANSF_ENVIADA, sin restar dos veces el importe.
    IF :NEW.TIPO IN ('DEPOSITO','TRANSF_RECIBIDA','INTERES') THEN
        :NEW.SALDO_POSTERIOR := v_saldo + :NEW.MONTO;
    ELSIF :NEW.TIPO IN ('RETIRO','TRANSF_ENVIADA','COMISION') THEN
        :NEW.SALDO_POSTERIOR := v_saldo - :NEW.MONTO;
    ELSE
        -- CK_MOV_TIPO rechaza el dominio inválido al comprobar la fila.
        :NEW.SALDO_POSTERIOR := v_saldo;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20002, 'Cuenta inexistente.');
END TRG_MOVIMIENTOS_BI;
/
-- @FIN

-- @OBJETO: TRG_MOVIMIENTOS_AI
CREATE OR REPLACE TRIGGER TRG_MOVIMIENTOS_AI
AFTER INSERT ON TBL_MOVIMIENTOS
FOR EACH ROW
BEGIN
    -- Único punto de actualización del saldo; sin consultar la tabla mutante.
    IF :NEW.TIPO IN ('DEPOSITO','TRANSF_RECIBIDA','INTERES') THEN
        UPDATE TBL_CUENTAS SET SALDO = SALDO + :NEW.MONTO
        WHERE ID_CUENTA = :NEW.ID_CUENTA;
    ELSIF :NEW.TIPO IN ('RETIRO','TRANSF_ENVIADA','COMISION') THEN
        UPDATE TBL_CUENTAS SET SALDO = SALDO - :NEW.MONTO
        WHERE ID_CUENTA = :NEW.ID_CUENTA;
    END IF;
    INSERT INTO TBL_AUDITORIA (
        ID_AUDITORIA, TABLA, OPERACION, ID_REGISTRO, USUARIO_BD, FECHA, DETALLE
    ) VALUES (
        SQ_AUDITORIA.NEXTVAL, 'TBL_MOVIMIENTOS', 'INSERT', :NEW.ID_MOVIMIENTO,
        USER, SYSTIMESTAMP,
        'Cuenta ' || :NEW.ID_CUENTA || '; tipo ' || :NEW.TIPO ||
        '; monto ' || :NEW.MONTO || '; saldo posterior ' || :NEW.SALDO_POSTERIOR
    );
END TRG_MOVIMIENTOS_AI;
/
-- @FIN

-- @OBJETO: TRG_CUENTAS_AU
CREATE OR REPLACE TRIGGER TRG_CUENTAS_AU
AFTER UPDATE OF ESTADO ON TBL_CUENTAS
FOR EACH ROW
BEGIN
    -- UPDATE de SALDO o FECHA_ULT_INTERES no dispara este trigger.
    IF :OLD.ESTADO <> :NEW.ESTADO THEN
        INSERT INTO TBL_AUDITORIA (
            ID_AUDITORIA, TABLA, OPERACION, ID_REGISTRO, USUARIO_BD, FECHA, DETALLE
        ) VALUES (
            SQ_AUDITORIA.NEXTVAL, 'TBL_CUENTAS', 'UPDATE', :NEW.ID_CUENTA,
            USER, SYSTIMESTAMP, 'Estado: ' || :OLD.ESTADO || ' -> ' || :NEW.ESTADO
        );
    END IF;
END TRG_CUENTAS_AU;
/
-- @FIN
