CREATE TABLE TBL_LIMITES_CATEGORIAS (
    ID_CONFIG NUMBER(1) CONSTRAINT PK_LIMITES_CATEGORIAS PRIMARY KEY,
    LIMITE_GOLD NUMBER(14,2) CONSTRAINT CK_LIMITES_GOLD_NN NOT NULL,
    LIMITE_PREMIUM NUMBER(14,2) CONSTRAINT CK_LIMITES_PREMIUM_NN NOT NULL,
    VERSION NUMBER(10) DEFAULT 1 CONSTRAINT CK_LIMITES_VERSION_NN NOT NULL,
    CONSTRAINT CK_LIMITES_CONFIG CHECK (ID_CONFIG = 1),
    CONSTRAINT CK_LIMITES_ORDEN CHECK (LIMITE_GOLD > 0 AND LIMITE_PREMIUM > LIMITE_GOLD),
    CONSTRAINT CK_LIMITES_VERSION CHECK (VERSION >= 1)
);
COMMENT ON TABLE TBL_LIMITES_CATEGORIAS IS 'Límites de saldo configurables para las categorías de clientes';
