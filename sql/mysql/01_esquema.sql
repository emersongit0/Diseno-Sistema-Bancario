-- @OBJETO: V_ESTADO_CUENTA
CREATE OR REPLACE VIEW V_ESTADO_CUENTA AS
SELECT c.ID_CUENTA,c.NRO_CUENTA,CONCAT(cli.NOMBRES,' ',cli.APELLIDOS) CLIENTE_COMPLETO,
 m.ID_MOVIMIENTO,m.TIPO,m.MONTO,m.SALDO_POSTERIOR,m.FECHA,m.DESCRIPCION
FROM TBL_MOVIMIENTOS m JOIN TBL_CUENTAS c ON c.ID_CUENTA=m.ID_CUENTA
JOIN TBL_CLIENTES cli ON cli.ID_CLIENTE=c.ID_CLIENTE;
-- @FIN

-- @OBJETO: V_CUENTAS_RESUMEN
CREATE OR REPLACE VIEW V_CUENTAS_RESUMEN AS
SELECT c.ID_CUENTA,c.NRO_CUENTA,CONCAT(cli.NOMBRES,' ',cli.APELLIDOS) TITULAR,
 cli.CATEGORIA,c.SALDO,c.ESTADO,COUNT(m.ID_MOVIMIENTO) CANTIDAD_MOVIMIENTOS,
 COALESCE(SUM(CASE WHEN m.TIPO IN ('DEPOSITO','TRANSF_RECIBIDA','INTERES') THEN m.MONTO ELSE 0 END),0) TOTAL_DEPOSITADO,
 COALESCE(SUM(CASE WHEN m.TIPO IN ('RETIRO','TRANSF_ENVIADA','COMISION') THEN m.MONTO ELSE 0 END),0) TOTAL_RETIRADO
FROM TBL_CUENTAS c JOIN TBL_CLIENTES cli ON cli.ID_CLIENTE=c.ID_CLIENTE
LEFT JOIN TBL_MOVIMIENTOS m ON m.ID_CUENTA=c.ID_CUENTA
GROUP BY c.ID_CUENTA,c.NRO_CUENTA,cli.NOMBRES,cli.APELLIDOS,cli.CATEGORIA,c.SALDO,c.ESTADO;
-- @FIN
