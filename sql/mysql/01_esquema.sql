-- @OBJETO: TBL_CLIENTES
CREATE TABLE TBL_CLIENTES (
 ID_CLIENTE BIGINT PRIMARY KEY AUTO_INCREMENT,
 DNI VARCHAR(8) NOT NULL,
 NOMBRES VARCHAR(100) NOT NULL,
 APELLIDOS VARCHAR(100) NOT NULL,
 EMAIL VARCHAR(254) NOT NULL,
 CATEGORIA VARCHAR(7) NOT NULL DEFAULT 'BASICO',
 FECHA_REGISTRO DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT UQ_CLIENTES_DNI UNIQUE (DNI),
 CONSTRAINT UQ_CLIENTES_EMAIL UNIQUE (EMAIL),
 CONSTRAINT CK_CLIENTES_DNI CHECK (REGEXP_LIKE(DNI,'^[0-9]{8}$')),
 CONSTRAINT CK_CLIENTES_CATEGORIA CHECK (CATEGORIA IN ('BASICO','GOLD','PREMIUM'))
) ENGINE=InnoDB;
-- @FIN

-- @OBJETO: TBL_CUENTAS
CREATE TABLE TBL_CUENTAS (
 ID_CUENTA BIGINT PRIMARY KEY,
 NRO_CUENTA VARCHAR(12) NOT NULL,
 ID_CLIENTE BIGINT NOT NULL,
 TIPO VARCHAR(9) NOT NULL,
 SALDO DECIMAL(14,2) NOT NULL DEFAULT 0,
 TASA_INTERES_ANUAL DECIMAL(5,2),
 ESTADO VARCHAR(9) NOT NULL DEFAULT 'ACTIVA',
 FECHA_APERTURA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FECHA_ULT_INTERES DATE,
 CONSTRAINT UQ_CUENTAS_NRO UNIQUE (NRO_CUENTA),
 CONSTRAINT FK_CUENTAS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES TBL_CLIENTES(ID_CLIENTE),
 CONSTRAINT CK_CUENTAS_TIPO CHECK (TIPO IN ('AHORROS','CORRIENTE')),
 CONSTRAINT CK_CUENTAS_ESTADO CHECK (ESTADO IN ('ACTIVA','BLOQUEADA')),
 CONSTRAINT CK_CUENTAS_SALDO CHECK (SALDO>=0)
) ENGINE=InnoDB;
-- @FIN

-- @OBJETO: TBL_MOVIMIENTOS
CREATE TABLE TBL_MOVIMIENTOS (
 ID_MOVIMIENTO BIGINT PRIMARY KEY AUTO_INCREMENT,
 ID_CUENTA BIGINT NOT NULL,
 TIPO VARCHAR(15) NOT NULL,
 MONTO DECIMAL(14,2) NOT NULL,
 SALDO_POSTERIOR DECIMAL(14,2) NOT NULL,
 FECHA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 DESCRIPCION VARCHAR(500),
 ID_CUENTA_RELACIONADA BIGINT,
 CONSTRAINT FK_MOV_CUENTA FOREIGN KEY (ID_CUENTA) REFERENCES TBL_CUENTAS(ID_CUENTA),
 CONSTRAINT FK_MOV_CUENTA_REL FOREIGN KEY (ID_CUENTA_RELACIONADA) REFERENCES TBL_CUENTAS(ID_CUENTA),
 CONSTRAINT CK_MOV_MONTO CHECK (MONTO>0),
 CONSTRAINT CK_MOV_TIPO CHECK (TIPO IN ('DEPOSITO','RETIRO','TRANSF_ENVIADA','TRANSF_RECIBIDA','INTERES','COMISION')),
 INDEX IX_MOV_CUENTA_FECHA (ID_CUENTA,FECHA,ID_MOVIMIENTO)
) ENGINE=InnoDB;
-- @FIN

-- @OBJETO: TBL_AUDITORIA
CREATE TABLE TBL_AUDITORIA (
 ID_AUDITORIA BIGINT PRIMARY KEY AUTO_INCREMENT,
 TABLA VARCHAR(128) NOT NULL,
 OPERACION VARCHAR(20) NOT NULL,
 ID_REGISTRO BIGINT NOT NULL,
 USUARIO_BD VARCHAR(288) NOT NULL,
 FECHA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 DETALLE VARCHAR(500)
) ENGINE=InnoDB;
-- @FIN

-- @OBJETO: TBL_LOG_ERRORES
CREATE TABLE TBL_LOG_ERRORES (
 ID_LOG BIGINT PRIMARY KEY AUTO_INCREMENT,
 PROCEDIMIENTO VARCHAR(128) NOT NULL,
 CODIGO INT NOT NULL,
 MENSAJE VARCHAR(4000) NOT NULL,
 FECHA DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB;
-- @FIN

-- @OBJETO: TBL_LIMITES_CATEGORIAS
CREATE TABLE TBL_LIMITES_CATEGORIAS (
 ID_CONFIG INT PRIMARY KEY,
 LIMITE_GOLD DECIMAL(14,2) NOT NULL,
 LIMITE_PREMIUM DECIMAL(14,2) NOT NULL,
 VERSION BIGINT NOT NULL DEFAULT 1,
 CONSTRAINT CK_LIMITES_CONFIG CHECK (ID_CONFIG=1),
 CONSTRAINT CK_LIMITES_ORDEN CHECK (LIMITE_GOLD>0 AND LIMITE_PREMIUM>LIMITE_GOLD),
 CONSTRAINT CK_LIMITES_VERSION CHECK (VERSION>=1)
) ENGINE=InnoDB;
-- @FIN

